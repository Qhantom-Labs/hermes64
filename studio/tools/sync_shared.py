"""Generate desktop/plugin.js and studio/prototype/dist/studio.bundle.js from the shared modules.

The desktop app loads plugin.js uncompiled and resolves only `@hermes/plugin-sdk`,
`react` and `react/jsx-runtime`, so the Studio's ES modules are inlined: each module
becomes an IIFE returning its exports, and `import {a, b as c} from './x.js'` becomes
`const {a, b: c} = __h64_x`. The same transform builds the classic-script bundle that
index.html loads under file:// (where Chromium refuses module scripts).

Stdlib only. Writes only files that are missing or carry the GENERATED marker, so a
hand-edited file is never clobbered; --check exits 1 if either output is stale.

    python3 -B studio/tools/sync_shared.py [--check]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROTO = ROOT / 'studio' / 'prototype'
MARK = '// GENERATED by studio/tools/sync_shared.py from studio/prototype/js/*.js, studio.css and studio/plugin/glue.js. Do not edit; edit the sources and re-run.'
ORDER = ['pixelfont', 'model', 'covers', 'motion', 'input', 'sound', 'cartridge', 'pattern', 'icons', 'state', 'app', 'rack']
IMPORT = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'\./([a-z]+)\.js'\s*;?\s*$", re.M)
EXPORT_DECL = re.compile(r'^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)', re.M)


def module(name):
    src = (PROTO / 'js' / (name + '.js')).read_text(encoding='utf-8')
    names = [m.group(2) for m in EXPORT_DECL.finditer(src)]

    def imp(m):
        dep = m.group(2)
        if dep not in ORDER or ORDER.index(dep) >= ORDER.index(name):
            raise SystemExit('module order: ' + name + ' imports ' + dep)
        parts = []
        for item in m.group(1).split(','):
            item = item.strip()
            if not item:
                continue
            a = re.fullmatch(r'([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?', item)
            if not a:
                raise SystemExit('cannot rewrite import in ' + name + ': ' + item)
            parts.append(a.group(1) + (': ' + a.group(2) if a.group(2) else ''))
        return 'const { ' + ', '.join(parts) + ' } = __h64_' + dep
    body = IMPORT.sub(imp, src)
    body = EXPORT_DECL.sub(lambda m: m.group(1) + ' ' + m.group(2), body)
    leftover = [ln for ln in body.splitlines() if re.match(r'\s*(import|export)\b', ln)]
    if leftover:
        raise SystemExit('unrewritten module syntax in ' + name + ': ' + leftover[0])
    return ('// ---- shared: studio/prototype/js/' + name + '.js ----\n'
            'const __h64_' + name + ' = (() => {\n' + body.rstrip() + '\n' +
            'return { ' + ', '.join(names) + ' }\n})()\n')


def modules():
    return '\n'.join(module(n) for n in ORDER)


def plugin_js():
    css = (PROTO / 'studio.css').read_text(encoding='utf-8')
    glue = (ROOT / 'studio' / 'plugin' / 'glue.js').read_text(encoding='utf-8')
    return (MARK + '\n'
            '// Hermes64 Studio desktop half: uncompiled ESM; imports only the three allowed specifiers.\n'
            "import { ROUTES_AREA, SIDEBAR_NAV_AREA, PANES_AREA, SandboxedFrame, host } from '@hermes/plugin-sdk'\n"
            "import { useEffect, useRef, useState } from 'react'\n"
            "import { jsx, jsxs } from 'react/jsx-runtime'\n\n" +
            modules() + '\n'
            'const { boot } = __h64_app\n'
            'const { bootRack } = __h64_rack\n'
            'const { backendErrorSentence } = __h64_model\n'
            'const STUDIO_CSS = ' + json.dumps(css) + '\n\n' + glue)


def bundle_js():
    sample = json.loads((PROTO / 'catalogue.sample.json').read_text(encoding='utf-8'))
    return (MARK + '\n'
            '// Classic-script build of the Studio prototype for file:// (index.html picks it).\n'
            '(function () {\n'
            "'use strict'\n"
            'window.H64_SAMPLE_CATALOGUE = ' + json.dumps(sample, separators=(',', ':')) + '\n' +
            modules() + '\n'
            "__h64_app.boot(document.getElementById('studio')).catch(function (err) {\n"
            '  window.__h64 = window.__h64 || { errors: [] }\n'
            '  window.__h64.errors.push(String(err && err.stack ? err.stack : err))\n'
            '})\n'
            '})()\n')


def sync(check=False):
    outputs = {ROOT / 'desktop' / 'plugin.js': plugin_js(), PROTO / 'dist' / 'studio.bundle.js': bundle_js()}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            print('up to date:', path.relative_to(ROOT))
            continue
        stale.append(path)
        if check:
            print('STALE:', path.relative_to(ROOT))
            continue
        if current is not None and not current.startswith(MARK):
            raise SystemExit('refusing to overwrite a file without the GENERATED marker: ' + str(path.relative_to(ROOT)))
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + '.tmp')
        tmp.write_text(text, encoding='utf-8')
        tmp.replace(path)
        print('wrote:', path.relative_to(ROOT), len(text.encode('utf-8')), 'bytes')
    return 1 if (check and stale) else 0


if __name__ == '__main__':
    sys.exit(sync('--check' in sys.argv[1:]))

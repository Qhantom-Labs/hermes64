"""Asset catalog (hermes64-catalog/1.0.0): stdlib validator, deterministic writer, project catalogs.

The repository catalog (catalog/catalog.json) is generated by tools/catalog.py from the
manifests and never hand-edited. A game project's catalog.json uses the same shape. It has two
writers, the hub (installs) and hermes64_character (characters built or bound), and one write
path: read_project -> upsert -> write_project, so either tool produces the same bytes and a
document the other can extend (MERGE4).
"""
import json
from pathlib import Path

from .safety import fail

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_ID = 'hermes64-catalog/1.0.0'
KINDS = ('person', 'creature', 'item', 'kit', 'sound', 'cover', 'style', 'pack', 'game')
VISIBILITY = ('public', 'public-with-notice', 'demo-only', 'internal')
SPECIAL_USERS = ('hermes64:new',)
HUB_KINDS = {'style': 'style', 'kit': 'kit', 'sound': 'sound', 'cover': 'cover', 'game': 'game'}
PROJECT_NOTE = ('Assets of this game: hub installs (/hermes64 hub install, with the archive hash each came from) and '
                'characters made or bound with hermes64_character. Written by Hermes64; one asset per line, sorted by id.')
PROJECT_LABEL = "game's catalog.json"
_SCHEMA = {}


def schema(root=ROOT):
    if 'doc' not in _SCHEMA:
        _SCHEMA['doc'] = json.loads((Path(root) / 'contracts/catalog/1.0.0.json').read_text(encoding='utf-8'))
    return _SCHEMA['doc']


def validate(doc, root=None, label='catalog'):
    """Schema + identity rules. With root, also checks that preview thumbnails exist."""
    from .style_profile import StyleError, validate_schema
    try:
        validate_schema(doc, schema(), schema())
    except StyleError as exc:
        fail('catalog_schema', 'The %s is malformed (%s); regenerate it with python3 -B -m tools.catalog build.'
             % (label, str(exc).split(': ', 1)[-1][:160]))
    ids = [asset['id'] for asset in doc['assets']]
    if ids != sorted(ids) or len(set(ids)) != len(ids):
        fail('catalog_ids', 'The %s must list unique asset ids in sorted order.' % label)
    known = set(ids) | set(SPECIAL_USERS)
    counts = {}
    for asset in doc['assets']:
        counts[asset['kind']] = counts.get(asset['kind'], 0) + 1
        missing = [user for user in asset['used_by'] if user not in known]
        if missing:
            fail('catalog_refs', 'The %s says %s is used by unknown %s.' % (label, asset['id'], missing[0]))
        if asset['kind'] == 'person' and 'placeholder' not in asset:
            fail('catalog_names', 'The %s must mark whether person %s has a placeholder name.' % (label, asset['id']))
        if asset['visibility'] == 'public-with-notice' and not asset.get('notice'):
            fail('catalog_notice', 'The %s lists %s as public-with-notice without its notice file.' % (label, asset['id']))
        if root is not None and asset['preview'] and not (Path(root) / asset['preview']).is_file():
            fail('catalog_preview', 'The %s points %s at a missing preview %s.' % (label, asset['id'], asset['preview']))
    if doc['counts'] != dict(sorted(counts.items())):
        fail('catalog_counts', 'The %s counts do not match its assets; regenerate it.' % label)
    return doc


def dumps(doc):
    """Deterministic bytes: one asset per line (diff-friendly, compact), sorted keys everywhere."""
    head = {key: value for key, value in doc.items() if key != 'assets'}
    rows = [json.dumps(asset, ensure_ascii=False, sort_keys=True, separators=(',', ':')) for asset in doc['assets']]
    body = json.dumps(head, ensure_ascii=False, sort_keys=True, indent=1, allow_nan=False)
    assets = ' "assets": [\n' + ',\n'.join('  ' + row for row in rows) + ('\n ],\n' if rows else ' ],\n')
    return ('{\n' + assets + body[2:] + '\n').encode('utf-8')


def load(path, label='catalog'):
    try:
        doc = json.loads(Path(path).read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        fail('catalog_read', 'Could not read the %s at %s (%s).' % (label, path, type(exc).__name__))
    return validate(doc, label=label)


# ---------------------------------------------------------------- project catalogs (hub installs + characters)
def empty_project_catalog():
    return {'schema': SCHEMA_ID, 'generated_by': 'hermes64', 'note': PROJECT_NOTE, 'counts': {}, 'assets': []}


def read_project(project):
    """A managed project's catalog.json, validated, or a fresh empty one."""
    if not project.path('catalog.json').is_file():
        return empty_project_catalog()
    try:
        doc = json.loads(project.path('catalog.json').read_bytes().decode('utf-8'))
    except (OSError, ValueError, UnicodeError):
        fail('catalog_read', "This game's catalog.json is not valid JSON; fix or move it, then install again.")
    return validate(doc, label=PROJECT_LABEL)


def installed(doc, entry_id):
    return next((asset for asset in doc['assets'] if asset.get('hub') == entry_id), None)


def hub_kind(entry):
    if entry['kind'] == 'character':
        return 'creature' if 'creature' in entry.get('tags', []) else 'person'
    return HUB_KINDS[entry['kind']]


def add_install(doc, entry, written, registry):
    """Return a new project catalog with one row for an installed hub entry. written: [(path, sha256, bytes)]."""
    from .hub_sources import clean_tags
    row = {'id': 'hub:' + entry['id'], 'name': entry['name'][:80], 'kind': hub_kind(entry), 'source_lane': 'hub',
           'source': registry[:200],
           'files': [{'path': path, 'sha256': digest, 'bytes': size} for path, digest, size in sorted(written)],
           'hashes': {'archive': entry['sha256']},
           'budgets': {'bytes': sum(size for _p, _d, size in written),
                       'tris_max': int((entry.get('budget') or {}).get('tris_max', 0))},
           'tags': clean_tags(entry.get('tags', []), 24), 'licence': entry['licence'],
           'provenance': ('Installed from the Hermes64 Hub (%s %s by %s); archive sha256 verified.'
                          % (entry['id'], entry['version'], entry['author']))[:300],
           'preview': None, 'visibility': entry['visibility'], 'used_by': [], 'style': entry['compat']['style'],
           'hub': entry['id'], 'status': 'installed',
           'installed': {'entry': entry['id'], 'version': entry['version'], 'sha256': entry['sha256'],
                         'registry': registry[:300]}}
    if row['kind'] == 'person':
        row['placeholder'] = False
    if entry.get('notice'):
        row['notice'] = entry['notice'][:200]
    rig = (entry.get('compat') or {}).get('rig')
    if rig and 'rig-' + rig.split('@')[0] not in row['tags']:
        row['tags'] = (['rig-' + rig.split('@')[0]] + row['tags'])[:24]      # same tag hermes64_character writes
    return upsert(doc, row)


def upsert(doc, row):
    """A new validated project catalog with `row` added or replacing the row with the same id (counts updated)."""
    assets = sorted([a for a in doc['assets'] if a['id'] != row['id']] + [row], key=lambda a: a['id'])
    counts = {}
    for asset in assets:
        counts[asset['kind']] = counts.get(asset['kind'], 0) + 1
    out = dict(doc, assets=assets, counts=dict(sorted(counts.items())))
    return validate(out, label=PROJECT_LABEL)


def write_project(project, doc):
    """The one write of a project's catalog.json (validated, deterministic bytes)."""
    project.write_bytes('catalog.json', dumps(validate(doc, label=PROJECT_LABEL)))
    return doc

def norm_word(w):
    w = w.lower()
    if len(w) > 4 and w.endswith("ies"):
        return w[:-3] + "y"
    if len(w) > 4 and w.endswith(("ches", "shes", "xes", "sses")):
        return w[:-2]
    if len(w) > 3 and w.endswith("s") and not w.endswith(("ss", "us", "is")):
        return w[:-1]
    return w


def norm_text(text):
    return " ".join(norm_word(t) for t in re.findall(r"[a-z0-9]+", str(text).lower().replace("-", " ")))


def _phrase_in(phrase, text):
    p = norm_text(phrase)
    return bool(p) and re.search(r"(^| )%s( |$)" % re.escape(p), text) is not None


def _index(vocab):
    out = []
    for term, syns in vocab.items():
        for s in [term.replace("_", " ")] + list(syns):
            out.append((norm_text(s), term))
    out.sort(key=lambda x: -len(x[0]))  # longest phrase first: "crystal ball" before "crystal"
    return out


KIND_INDEX = _index(KINDS)
GENRE_INDEX = _index(GENRES)


def terms_in(text, index):
    """Canonical terms named in text, longest phrases first; a matched phrase hides its sub-words."""
    t = " %s " % norm_text(text)
    found = []
    for phrase, term in index:
        pat = " %s " % phrase
        if phrase and pat in t:
            if term not in found:
                found.append(term)
            t = t.replace(pat, " | ")
    return found


def kinds_in(text):
    return terms_in(text, KIND_INDEX)


def genres_in(text):
    return terms_in(text, GENRE_INDEX)


def split_terms(want):
    """(kind terms, genre terms) named in a want. Kind phrases are consumed first, so 'castle' or 'cave' count as
    kinds when they are kinds, and genre words are read from what is left ('haunted lighthouse' -> horror +
    lighthouse)."""
    t = " %s " % norm_text(want)
    kinds = []
    for phrase, term in KIND_INDEX:
        pat = " %s " % phrase
        if phrase and pat in t:
            if term not in kinds:
                kinds.append(term)
            t = t.replace(pat, " | ")
    return kinds, terms_in(t, GENRE_INDEX)


# ------------------------------------------------------------------------------------------- data access
_CACHE = {}


def load(path=TAGS):
    key = str(path)
    if key not in _CACHE:
        _CACHE[key] = json.loads(Path(path).read_text(encoding="utf-8"))
    return _CACHE[key]


def rows(data=None):
    return (data or load())["rows"]


def validate(data):
    """Errors in a tags document (empty list = valid): closed vocabulary per axis, unique ids, a kind per row."""
    err = []
    if data.get("format") != FORMAT:
        err.append("format must be %s" % FORMAT)
    allowed = {"genre": set(GENRES), "kind": set(KINDS) | {"unclassified"}, "shape": set(SHAPES),
               "use": set(USES), "place": set(PLACES)}
    seen = set()
    for r in data.get("rows", []):
        rid = r.get("id")
        if not rid or rid in seen:
            err.append("duplicate or empty id %r" % rid)
        seen.add(rid)
        if not r.get("kind"):
            err.append("%s: no kind" % rid)
        for axis, ok in allowed.items():
            bad = [x for x in r.get(axis, []) if x not in ok]
            if bad:
                err.append("%s: %s terms outside the vocabulary: %s" % (rid, axis, bad))
        if r.get("scale") not in SCALES:
            err.append("%s: scale %r outside the vocabulary" % (rid, r.get("scale")))
        if (r.get("review") or {}).get("status") not in ("mechanical", "needs_review", "reviewed"):
            err.append("%s: review.status missing" % rid)
    return err


# ------------------------------------------------------------------------------------------- find
def find(want, brief=None, data=None, limit=10):
    """Rank pieces for a free-text want (<= 60 chars per the brief contract). Returns [(id, score, why)]."""
    want = str(want)[:120]
    want_kinds = kinds_in(want)
    want_genres = genres_in(want)
    want_norm = norm_text(want)
    want_words = {w for w in want_norm.split() if len(w) > 2 and w not in STOP}
    ctx = set()
    if brief:
        setting = brief.get("setting", {}) if isinstance(brief, dict) else {}
        ctx = set(genres_in(" ".join(str(v) for v in setting.values())))
        ctx |= set(genres_in(str(brief.get("prompt", "")))) if isinstance(brief, dict) else set()
    out = []
    for r in rows(data):
        score, why = 0.0, []
        rk = r["kind"]
        hit = [k for k in want_kinds if k in rk]
        if hit:
            score += 0.6
            why.append("kind %s" % "/".join(hit))
        else:
            syn = [s for s in r.get("synonyms", []) if _phrase_in(s, want_norm)]
            if syn:
                score += 0.55
                why.append("synonym '%s'" % syn[0])
            else:
                rel = [k for k in want_kinds if any(x in rk for x in RELATED.get(k, ()))]
                if rel:
                    score += 0.3
                    why.append("related to %s" % rel[0])
        g = [x for x in want_genres if x in r["genre"]]
        if g:
            score += min(0.2, 0.1 * len(g))
            why.append("genre %s" % "/".join(g))
        dwords = set(norm_text(r.get("name", "") + " " + r.get("description", "")).split())
        d = sorted(want_words & dwords)
        if d:
            score += min(0.15, 0.05 * len(d))
            why.append("words %s" % ",".join(d[:3]))
        c = sorted(ctx & set(r["genre"]))
        if c and score > 0:
            score += min(0.1, 0.05 * len(c))
            why.append("fits brief %s" % "/".join(c))
        if score > 0:
            out.append((r["id"], round(min(score, 1.0), 3), why))
    out.sort(key=lambda x: (-x[1], x[0]))
    return out[:limit]


# ------------------------------------------------------------------------------------------- gap report
def _kind_status(term, rs):
    ids = sorted(r["id"] for r in rs if term in r["kind"])
    if ids:
        return "exists", ids, "%d pieces of kind '%s'" % (len(ids), term)
    rel = RELATED.get(term, [])
    ids = sorted(r["id"] for r in rs if any(k in r["kind"] for k in rel))
    if ids:
        return "partial", ids, "no '%s' piece; stand-in kinds %s" % (term, "/".join(rel))
    return "missing", [], "known kind '%s', no piece in the library" % term


def _genre_status(term, rs):
    ids = sorted(r["id"] for r in rs if term in r["genre"])
    status = "exists" if len(ids) >= GENRE_EXISTS_MIN else ("partial" if ids else "missing")
    return status, ids, "%d pieces tagged genre '%s'" % (len(ids), term)


def gap_row(want, data=None, brief=None):
    """Status of one wanted tag or phrase. Every named term must exist for 'exists'; any missing or partial term
    makes the phrase partial (or missing when nothing at all matches). Never a silent substitute."""
    rs = rows(data)
    kinds, genres = split_terms(want)
    parts = [("kind", k) + _kind_status(k, rs) for k in kinds] + [("genre", g) + _genre_status(g, rs) for g in genres]
    ranked = find(want, brief=brief, data=data, limit=50)
    if not parts:
        syn = [x for x in ranked if any(w.startswith("synonym") for w in x[2])]
        if syn:
            return {"want": want, "axis": "free", "terms": [], "status": "exists", "count": len(syn),
                    "matches": [x[0] for x in syn[:12]], "why": "; ".join(syn[0][2]), "parts": [],
                    "next": _next("exists")}
        words = [x for x in ranked if x[1] > 0]
        # an unknown noun is a gap, never replaced: loose description-word hits are hints, not stand-ins
        return {"want": want, "axis": "free", "terms": [], "status": "missing", "count": 0, "matches": [],
                "hints": [x[0] for x in words[:5]], "unknown_term": True, "parts": [],
                "why": "word not in the controlled vocabulary; nothing is substituted" +
                       (" (loose word hints: %s)" % ", ".join(x[0] for x in words[:3]) if words else ""),
                "next": _next("missing")}
    statuses = [p[2] for p in parts]
    if all(s == "exists" for s in statuses):
        status = "exists"
    elif all(s == "missing" for s in statuses):
        status = "missing"
    else:
        status = "partial"
    # matches: pieces that satisfy the kind terms (or the genre terms when the want names no kind), best first
    need = [p for p in parts if p[0] == "kind"] or parts
    keep = set.intersection(*[set(p[3]) for p in need]) if all(p[3] for p in need) else set().union(*[set(p[3]) for p in need])
    order = [x[0] for x in ranked if x[0] in keep] + sorted(keep - {x[0] for x in ranked})
    weakest = [p for p in parts if p[2] != "exists"]
    why = "; ".join(p[4] for p in (weakest or parts))
    return {"want": want, "axis": "+".join(sorted({p[0] for p in parts})), "terms": [p[1] for p in parts],
            "status": status, "count": len(keep), "matches": order[:12], "why": why,
            "parts": [{"axis": p[0], "term": p[1], "status": p[2], "count": len(p[3])} for p in parts],
            "next": _next(status)}


def _next(status):
    return {"exists": "use the library piece (rebuild in the project's mood pack)",
            "partial": "name the stand-in in the asset report, or generate/convert a real one",
            "missing": "generate (recipe or python) or convert a user model; otherwise report as failed"}[status]


def wanted_from_brief(brief):
    out = []
    setting = brief.get("setting", {})
    for k in ("genre",):
        if setting.get(k):
            out.append(str(setting[k]))
    out += [str(b) for b in brief.get("build_types", [])]
    out += [str(p.get("want")) for p in brief.get("props", []) if p.get("want")]
    return out


def gap_report(wanted, data=None, brief=None):
    seen, rows_out = [], []
    for w in wanted:
        w = str(w).strip()
        if w and w.lower() not in seen:
            seen.append(w.lower())
            rows_out.append(gap_row(w, data=data, brief=brief))
    summary = {s: [r["want"] for r in rows_out if r["status"] == s] for s in ("exists", "partial", "missing")}
    return {"format": GAP_FORMAT, "rows": rows_out, "summary": summary,
            "counts": {k: len(v) for k, v in summary.items()},
            "note": "exists = a library piece answers the want; partial = only a named stand-in or too few pieces; "
                    "missing = nothing, so it must be generated, converted or reported failed. Mechanical tags, "
                    "Fable review pending (docs/ABIBLE-REVIEW-NEEDED.md)."}


def report_lines(rep):
    lines = ["Library check: %d exist, %d partial, %d missing." % (rep["counts"]["exists"], rep["counts"]["partial"],
                                                                  rep["counts"]["missing"])]
    for status in ("missing", "partial", "exists"):
        for r in rep["rows"]:
            if r["status"] == status:
                lines.append("  %-7s %-28s %s%s" % (status, r["want"][:28], r["why"][:70],
                                                    (" -> " + ", ".join(r["matches"][:3])) if r["matches"] else ""))
    return lines


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] not in ("find", "gaps"):
        print("usage: python3 -B -m adventure_maker.taxonomy find <want> | gaps <tag>... | gaps --brief <brief.json>")
        return 2
    if argv[0] == "find":
        for gid, score, why in find(" ".join(argv[1:])):
            print("%.2f %-24s %s" % (score, gid, "; ".join(why)))
        return 0
    brief = None
    wanted = argv[1:]
    if wanted[:1] == ["--brief"]:
        brief = json.loads(Path(wanted[1]).read_text(encoding="utf-8"))
        wanted = wanted_from_brief(brief) + wanted[2:]
    rep = gap_report(wanted, brief=brief)
    print("\n".join(report_lines(rep)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

def supported(text):
    return all(ch.upper() in GLYPHS for ch in text)


def _glyph(ch, letter):
    rows = GLYPHS.get(ch.upper(), GLYPHS['?'])
    if letter == 'tall':
        out = []
        for i, r in enumerate(rows):
            out.append(r)
            if i % 2 == 1:
                out.append(r)  # 9 -> 13 rows (3:2-ish), stems stay 2 px wide
        return out
    return list(rows)


def line_mask(text, letter='block'):
    """One line of text -> (w, h, bytearray mask 0/1) at base scale (glyph height 9, tall 13)."""
    glyphs = [_glyph(ch, letter) for ch in text]
    h = len(glyphs[0]) if glyphs else ROWS
    w = sum(len(g[0]) for g in glyphs) + GAP * max(0, len(glyphs) - 1)
    shear = h // 3 if letter == 'wedge' else 0
    w += shear
    m = bytearray(w * h)
    x0 = 0
    for g in glyphs:
        gw = len(g[0])
        for y, row in enumerate(g):
            dx = shear - (y // 3) if letter == 'wedge' else 0
            for x, c in enumerate(row):
                if c == '#':
                    m[y * w + x0 + x + dx] = 1
        x0 += gw + GAP
    return w, h, m


def wrap(text, letter, max_w, max_lines=2):
    """Greedy word wrap at base scale; returns lines (at most max_lines, last line may overflow)."""
    words = text.split(' ')
    lines, cur = [], ''
    for word in words:
        trial = (cur + ' ' + word).strip()
        if cur and line_mask(trial, letter)[0] > max_w and len(lines) < max_lines - 1:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    lines.append(cur)
    return lines


def text_mask(lines, letter='block', align='center'):
    """Lines -> (w, h, mask) at base scale."""
    masks = [line_mask(t, letter) for t in lines]
    w = max(m[0] for m in masks)
    lh = masks[0][1]
    h = lh * len(masks) + LINE_GAP * (len(masks) - 1)
    out = bytearray(w * h)
    for i, (mw, mh, mm) in enumerate(masks):
        ox = (w - mw) // 2 if align == 'center' else (0 if align == 'left' else w - mw)
        oy = i * (lh + LINE_GAP)
        for y in range(mh):
            out[(oy + y) * w + ox:(oy + y) * w + ox + mw] = mm[y * mw:(y + 1) * mw]
    return w, h, out


def small_mask(text):
    """3x5 label face, 1 px gaps -> (w, h, mask)."""
    text = text.upper()
    w = 4 * len(text) - 1 if text else 1
    h = 5
    m = bytearray(max(1, w) * h)
    for i, ch in enumerate(text):
        g = SMALL.get(ch, SMALL[' '])
        for r in range(5):
            for c in range(3):
                if g[r * 3 + c] == '1':
                    m[r * w + i * 4 + c] = 1
    return max(1, w), h, m

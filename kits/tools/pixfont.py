"""Tiny original 3x5 pixel font for contact-sheet labels (numpy)."""
import numpy as np

_G = {
    "A": "010101111101101", "B": "110101110101110", "C": "011100100100011", "D": "110101101101110",
    "E": "111100110100111", "F": "111100110100100", "G": "011100101101011", "H": "101101111101101",
    "I": "111010010010111", "J": "001001001101010", "K": "101101110101101", "L": "100100100100111",
    "M": "101111111101101", "N": "110101101101101", "O": "010101101101010", "P": "110101110100100",
    "Q": "010101101111011", "R": "110101110101101", "S": "011100010001110", "T": "111010010010010",
    "U": "101101101101111", "V": "101101101101010", "W": "101101111111101", "X": "101101010101101",
    "Y": "101101010010010", "Z": "111001010100111", "0": "111101101101111", "1": "010110010010111",
    "2": "110001010100111", "3": "110001010001110", "4": "101101111001001", "5": "111100110001110",
    "6": "011100111101111", "7": "111001010010010", "8": "111101111101111", "9": "111101111001110",
    ".": "000000000000010", "_": "000000000000111", "-": "000000111000000", " ": "000000000000000",
    ":": "000010000010000", "/": "001001010100100", "=": "000111000111000", "(": "010100100100010",
    ")": "010001001001010", "+": "000010111010000", ",": "000000000010100",
}


def text_mask(s, scale=1):
    s = s.upper()
    w = len(s) * 4
    m = np.zeros((5, max(1, w)), dtype=bool)
    for i, ch in enumerate(s):
        g = _G.get(ch, _G[" "])
        for r in range(5):
            for c in range(3):
                if g[r * 3 + c] == "1":
                    m[r, i * 4 + c] = True
    if scale > 1:
        m = np.repeat(np.repeat(m, scale, 0), scale, 1)
    return m


def draw_text(img, s, x, y, color, scale=1, shadow=(0, 0, 0)):
    m = text_mask(s, scale)
    h, w = m.shape
    H, W = img.shape[:2]
    for dx, dy, col in ((1, 1, shadow), (0, 0, color)):
        if col is None:
            continue
        ys, xs = np.nonzero(m)
        ys = ys + y + dy
        xs = xs + x + dx
        ok = (ys >= 0) & (ys < H) & (xs >= 0) & (xs < W)
        img[ys[ok], xs[ok], :3] = col
    return img
